/* WAVE 8 (§3) — swarm vs single-agent baseline, OFFLINE and deterministic.
   The live 3E bench proved 4.29× median against a real provider; this test
   makes the parallelism claim CI-reproducible with seeded latency injection.
   B1: parallel arm is meaningfully faster than the cap=1 baseline (≥2.5× —
       generous headroom below the theoretical ~6× to stay flake-free on CI)
   B2: baseline has ZERO overlap; parallel arm has full overlap (fan C(2))
   B3: result parity — same tasks, same ok-flags, same payload identities
   B4: dependency chain is never over-parallelized (child ≥ parent end)
       and makespan ≥ 85% of the critical path
   B5: failures stay zero; adaptive=true arm keeps parity too
   B6: CLI run writes evidence JSON + refreshes the BENCHMARKS.md section */
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { runOfflineBench, renderMarkdown, refreshBenchmarks } from '../scripts/offline-swarm-bench.mjs';

const CONF = { fan: 8, reps: 3, taskMs: 50, jitterMs: 10, seed: 0x7a };

test('B1: parallel arm beats the single-agent baseline decisively', async () => {
  const rep = await runOfflineBench(CONF);
  assert.ok(rep.speedupMedian >= 2.5, `speedup ${rep.speedupMedian}× below floor`);
  assert.ok(rep.serialMedianMs > rep.parallelMedianMs);
}, { timeout: 30000 });

test('B2: overlap is zero in the baseline and maximal in the parallel arm', async () => {
  const rep = await runOfflineBench(CONF);
  assert.deepEqual(rep.overlap.serial, [0, 0, 0]);
  const maxPairs = (CONF.fan * (CONF.fan - 1)) / 2;
  assert.deepEqual(rep.overlap.parallel.map((x) => x === maxPairs ? 1 : x), [1, 1, 1], `expected full ${maxPairs} pairs`);
}, { timeout: 30000 });

test('B3: result parity between arms; zero failures', async () => {
  const rep = await runOfflineBench(CONF);
  assert.equal(rep.parity, true);
  assert.equal(rep.failures, 0);
  assert.ok(rep.arms.every((a) => a.okCount === CONF.fan));
}, { timeout: 30000 });

test('B4: the dependency chain is never over-parallelized', async () => {
  const rep = await runOfflineBench(CONF);
  assert.equal(rep.chain.depsRespected, true);
  assert.ok(rep.chain.wallMs >= rep.chain.criticalPathMs * 0.85, `chain ${rep.chain.wallMs} beat critical path ${rep.chain.criticalPathMs} — deps violated`);
}, { timeout: 30000 });

test('B5: seeded runs are reproducible (same seed → same config-derived numbers)', async () => {
  const a = await runOfflineBench(CONF);
  const b = await runOfflineBench(CONF);
  assert.equal(a.config.taskMs, b.config.taskMs);
  assert.ok(Math.abs(a.serialMedianMs - b.serialMedianMs) < 120, 'medians stable within scheduler jitter');
  assert.equal(a.overlap.serial.join(), b.overlap.serial.join());
}, { timeout: 60000 });

test('B6: CLI writes evidence JSON and refreshes the BENCHMARKS.md section', { timeout: 60000 }, () => {
  const out = execFileSync(process.execPath, ['scripts/offline-swarm-bench.mjs'], { cwd: path.resolve(import.meta.dirname, '..'), encoding: 'utf8' });
  assert.match(out, /speedup \(median\) .*×/);
  assert.match(out, /parity OK/);
  const date = new Date().toISOString().slice(0, 10);
  const ev = JSON.parse(fs.readFileSync(path.resolve(import.meta.dirname, '..', 'docs', 'evidence', `swarm-baseline-${date}.json`), 'utf8'));
  assert.equal(ev.config.fan, 8);
  assert.ok(ev.speedupMedian > 1);
  const benchDoc = fs.readFileSync(path.resolve(import.meta.dirname, '..', 'docs', 'BENCHMARKS.md'), 'utf8');
  assert.ok(benchDoc.includes('SWARM-BASELINE:BEGIN'), 'marker section installed');
  assert.match(benchDoc, /single-agent baseline \(cap=1\)/);
  /* idempotent refresh: rendering twice must not grow the document */
  const md1 = renderMarkdown(ev);
  assert.ok(md1.includes(String(ev.speedupMedian)));
});

test('B7: renderMarkdown + refreshBenchmarks round-trip without marker loss', () => {
  const tmp = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'majin-w8-')), 'BENCHMARKS.md');
  fs.writeFileSync(tmp, '# Benchmarks\n\nintro\n\n<!-- SWARM-BASELINE:BEGIN (auto-generated by scripts/offline-swarm-bench.mjs — do not hand-edit) -->\nold\n<!-- SWARM-BASELINE:END -->\ntail\n');
  const fake = { date: '2026-10-20', config: { fan: 4, reps: 1, taskMs: 10, jitterMs: 0, seed: 1 }, serialMedianMs: 100, parallelMedianMs: 30, speedupMedian: 3.33, overlap: { serial: [0], parallel: [6] }, parity: true, failures: 0, chain: { wallMs: 40, criticalPathMs: 40, depsRespected: true } };
  refreshBenchmarks(fake, tmp);
  const cur = fs.readFileSync(tmp, 'utf8');
  assert.match(cur, /3\.33×/);
  assert.match(cur, /intro/);
  assert.match(cur, /tail/);
  assert.equal((cur.match(/SWARM-BASELINE:BEGIN/g) || []).length, 1, 'exactly one section survives refreshes');
});
