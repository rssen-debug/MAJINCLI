import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createV5Server } from '../../src/v5/server.js';
import { ProviderAgent } from '../../src/v5/provider-agent.js';
if (!process.env.MAJIN_GO_TEST_KEY) throw new Error('MAJIN_GO_TEST_KEY is required; this live check makes paid provider calls.');
const dataDir=path.join(path.resolve(process.env.MAJIN_LIVE_STATE || '../provider-resume-live'), randomUUID());
const server=createV5Server({dataDir});
const key=process.env.MAJIN_GO_TEST_KEY;
await server.architect.providers.configureProvider({providerId:'opencode-go',apiKey:key});
server.architect.providers.selectModel({providerId:'opencode-go',modelId:'deepseek-v4-pro',allowManualFallback:true});
const nonce=randomUUID();
server.providerAgent.maxRounds=1;
const initial=await server.providerAgent.execute({goalText:`Owner-authorized file test, no network actions. Overall objective: write ${nonce} to once.txt exactly once and later create final.txt containing ${nonce}. For this first invocation only: use fs_write with append:true to append ${nonce} to once.txt exactly once. Do not create final.txt until a later resume instruction.`,criteria:[{kind:'file',path:'final.txt',contains:nonce}]});
assert.equal(initial.status,'BLOCKED');
assert.equal(fs.readFileSync(path.join(server.architect.workspaceDir,'once.txt'),'utf8'),nonce);
const restored=new ProviderAgent({architect:server.architect});
const result=await restored.execute({resume:true,goalText:`Resume phase two. once.txt has already been appended successfully; do not modify it again. Read it, write ${nonce} to final.txt, read final.txt, then report.`});
assert.equal(result.goal_id,initial.goal_id);
assert.equal(result.status,'COMPLETED');
assert.equal(result.criteria.length,1);
assert.equal(fs.readFileSync(path.join(server.architect.workspaceDir,'once.txt'),'utf8'),nonce);
assert.equal(fs.readFileSync(path.join(server.architect.workspaceDir,'final.txt'),'utf8'),nonce);
const proof={model:'deepseek-v4-pro',status:result.status,sameGoalId:true,preservedCriteria:true,appendExactlyOnce:true,resumedAfterAgentReconstruction:true,modelCalls:result.cost.modelCalls,toolCount:result.tool_results.length,verified:result.verification_evidence.length};
fs.writeFileSync(path.join(dataDir,'resume-proof.json'),JSON.stringify(proof,null,2));
console.log(JSON.stringify(proof));
