import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { createV5Server } from '../../src/v5/server.js';
const root=path.resolve(process.env.MAJIN_LIVE_STATE || '../provider-coding-live',randomUUID());
const server=createV5Server({dataDir:root});
const key=process.env.MAJIN_GO_TEST_KEY;
if(!key)throw new Error('MAJIN_GO_TEST_KEY is required; this live test makes paid provider calls.');
await server.architect.providers.configureProvider({providerId:'opencode-go',apiKey:key});
server.architect.providers.selectModel({providerId:'opencode-go',modelId:'deepseek-v4-pro',allowManualFallback:true});
server.architect.files.enableOwnerMode({lanes:['files','shell'],folders:[server.architect.workspaceDir]});
const started=performance.now();
const goal=await server.providerAgent.execute({goalText:'Authorized controlled coding acceptance. Build a tiny dependency-free Node ESM calculator CLI in app.mjs exporting add(a,b), and app.test.mjs with node:test cases for positive, negative and zero. CLI node app.mjs 2 3 must print 5; importing the module must not run CLI output. Use deterministic files and shell_run to actually syntax-check, run automated tests, and execute the CLI. Recover if anything fails. No network, package installs or other applications. Do the work, do not just explain it.',criteria:[{kind:'file',path:'app.mjs',contains:'add'},{kind:'file',path:'app.test.mjs',contains:'node:test'}]});
assert.equal(goal.status,'COMPLETED',goal.blocker||goal.model_reply);
assert(goal.tool_results.some(x=>x.tool==='shell_run'&&x.ok),'selected model must execute the app/test commands');
const cwd=server.architect.workspaceDir;
execFileSync(process.execPath,['--check','app.mjs'],{cwd,encoding:'utf8'});
const tests=execFileSync(process.execPath,['--test','app.test.mjs'],{cwd,encoding:'utf8'});
assert.match(tests,/(?:pass [3-9]|tests [3-9])/);
assert.equal(execFileSync(process.execPath,['app.mjs','2','3'],{cwd,encoding:'utf8'}).trim(),'5');
assert.equal(execFileSync(process.execPath,['app.mjs','-4','1'],{cwd,encoding:'utf8'}).trim(),'-3');
const proof={scenario:'C_coding',model:'deepseek-v4-pro',liveInference:true,modelExecutedCommands:true,independentSyntaxCheck:true,independentAutomatedTests:true,independentCliExamples:2,elapsedMs:Math.round(performance.now()-started),modelCalls:goal.cost.modelCalls,toolCalls:goal.tool_results.length,status:'passed'};
fs.writeFileSync(path.join(root,'coding-proof.json'),JSON.stringify(proof,null,2));
console.log(JSON.stringify(proof));
