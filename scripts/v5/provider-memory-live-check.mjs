import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createV5Server } from '../../src/v5/server.js';
const dataDir=path.resolve(process.env.MAJIN_LIVE_STATE || '../provider-memory-live',randomUUID());
let server=createV5Server({dataDir});
const key=process.env.MAJIN_GO_TEST_KEY;
if(!key)throw new Error('MAJIN_GO_TEST_KEY is required; this live test makes paid provider calls.');
await server.architect.providers.configureProvider({providerId:'opencode-go',apiKey:key});
server.architect.providers.selectModel({providerId:'opencode-go',modelId:'deepseek-v4-pro',allowManualFallback:true});
const started=performance.now();
const first=await server.providerAgent.execute({goalText:'Controlled learning acceptance: create first.txt containing exactly FIRST_ACCEPTANCE and read it back.',criteria:[{kind:'file',path:'first.txt',contains:'FIRST_ACCEPTANCE'}]});
assert.equal(first.status,'COMPLETED',first.blocker);
assert(server.architect.learning.state.procedures.length>0);
const before=server.architect.learning.state.procedures.length;
const procedureText=fs.readFileSync(path.join(dataDir,'learned-procedures.json'),'utf8');
assert(!procedureText.includes('first.txt'));
assert(!procedureText.includes('FIRST_ACCEPTANCE'));
server=createV5Server({dataDir});
const second=await server.providerAgent.execute({goalText:'Controlled reuse acceptance after restart. Use procedures_search to find the verified file-writing method, then procedures_read to read that method. Use its guidance to create second.txt containing exactly SECOND_ACCEPTANCE and read it back. Do not modify first.txt. Finish the actual file task.',criteria:[{kind:'file',path:'second.txt',contains:'SECOND_ACCEPTANCE'}]});
assert.equal(second.status,'COMPLETED',second.blocker||second.model_reply);
for(const name of ['procedures_search','procedures_read','fs_write'])assert(second.tool_results.some(x=>x.tool===name&&x.ok),name+' was not executed');
assert.equal(fs.readFileSync(path.join(server.architect.workspaceDir,'first.txt'),'utf8'),'FIRST_ACCEPTANCE');
assert.equal(fs.readFileSync(path.join(server.architect.workspaceDir,'second.txt'),'utf8'),'SECOND_ACCEPTANCE');
const proof={scenario:'F_procedural_memory',model:'deepseek-v4-pro',liveInference:true,learnedVerifiedProcedure:true,persistedProcedures:before,reconstructedArchitect:true,modelSearched:true,modelRead:true,independentNewFileVerification:true,originalFileUnchanged:true,parameterValuesAbsentFromProcedure:true,elapsedMs:Math.round(performance.now()-started),modelCalls:first.cost.modelCalls+second.cost.modelCalls,toolCalls:first.tool_results.length+second.tool_results.length,status:'passed'};
fs.writeFileSync(path.join(dataDir,'memory-proof.json'),JSON.stringify(proof,null,2));
console.log(JSON.stringify(proof));
